import fs from 'fs';
import path from 'path';
import { spawnSync } from 'child_process';
import { ZipArchive } from 'archiver';

/**
 * Builds a deployment package.
 *
 *   node scripts/package-deploy.mjs --preview
 *       -> rivora-preview.zip (noindex, for client review only)
 *
 *   node scripts/package-deploy.mjs
 *       -> rivora-deploy.zip (production)
 *
 * A production package is only created when `npm run build` succeeds. The
 * build intentionally fails while sample or unapproved reviews remain, so this
 * script cannot produce a launch package ahead of client approval.
 *
 * Layout inside the zip:
 *   DEPLOY.md
 *   public_html/          <- document root
 *   rivora-config/        <- outside the web root
 */

const preview = process.argv.includes('--preview');
const mode = preview ? 'preview' : 'production';
const root = process.cwd();
const dist = path.join(root, 'dist');
const staging = path.join(root, 'screenshots', `package-${mode}`);
const zipName = preview ? 'rivora-preview.zip' : 'rivora-deploy.zip';
const zipPath = path.join(root, zipName);

function fail(message) {
  console.error(`\nPackage failed: ${message}\n`);
  process.exit(1);
}

const siteUrl =
  (process.env.PUBLIC_SITE_URL || '').trim() || (preview ? 'https://preview.invalid' : '');

if (!preview && !siteUrl) {
  fail('set PUBLIC_SITE_URL to the live HTTPS origin before packaging production.');
}

const buildEnv = {
  ...process.env,
  PUBLIC_SITE_ENV: mode,
  PUBLIC_SITE_URL: siteUrl,
};

console.log(`\nBuilding ${mode} site${preview ? ' (noindex)' : ''}...`);
const npmCommand = process.platform === 'win32' ? process.env.ComSpec || 'cmd.exe' : 'npm';
const npmArgs =
  process.platform === 'win32'
    ? ['/d', '/s', '/c', 'npm run build']
    : ['run', 'build'];
const build = spawnSync(npmCommand, npmArgs, {
  cwd: root,
  env: buildEnv,
  stdio: 'inherit',
});

if (build.status !== 0) {
  fail(
    mode === 'production'
      ? 'the production build was blocked. This is expected while sample or unapproved reviews remain.'
      : 'the preview build failed.'
  );
}

const required = [
  'index.html',
  '404.html',
  'privacy-policy/index.html',
  'terms-and-conditions/index.html',
  'robots.txt',
  'sitemap.xml',
  'images/og-rivora.jpg',
  'api/contact.php',
  '.htaccess',
  '_headers',
];

for (const file of required) {
  if (!fs.existsSync(path.join(dist, file))) {
    fail(`dist/${file} is missing from the build.`);
  }
}

fs.rmSync(staging, { recursive: true, force: true });
fs.mkdirSync(path.join(staging, 'public_html'), { recursive: true });
fs.cpSync(dist, path.join(staging, 'public_html'), { recursive: true });

// Explicitly set build mode in packaged contact API
const apiTarget = path.join(staging, 'public_html', 'api');
fs.mkdirSync(apiTarget, { recursive: true });
fs.writeFileSync(
  path.join(apiTarget, 'build-mode.php'),
  `<?php\n// Generated by package-deploy.mjs\ndefine('RIVORA_BUILD_MODE', '${mode}');\n`
);

if (preview) {
  const htaccessPath = path.join(staging, 'public_html', '.htaccess');
  if (fs.existsSync(htaccessPath)) {
    const ht = fs.readFileSync(htaccessPath, 'utf-8');
    fs.writeFileSync(
      htaccessPath,
      ht.replace(
        '<IfModule mod_headers.c>',
        '<IfModule mod_headers.c>\n  Header always set X-Robots-Tag "noindex, nofollow"'
      )
    );
  }
  const headersPath = path.join(staging, 'public_html', '_headers');
  if (fs.existsSync(headersPath)) {
    const hd = fs.readFileSync(headersPath, 'utf-8');
    fs.writeFileSync(
      headersPath,
      hd.replace('/*', '/*\n  X-Robots-Tag: noindex, nofollow')
    );
  }
}

const configTarget = path.join(staging, 'rivora-config');
fs.mkdirSync(configTarget, { recursive: true });
fs.copyFileSync(
  path.join(root, 'rivora-config', '.env.example'),
  path.join(configTarget, '.env.example')
);
fs.cpSync(path.join(root, 'rivora-config', 'vendor'), path.join(configTarget, 'vendor'), {
  recursive: true,
});
fs.copyFileSync(path.join(root, 'DEPLOY.md'), path.join(staging, 'DEPLOY.md'));

// Never ship a real .env or rate-limit state, even if one exists locally.
for (const forbidden of ['.env', 'rate-limit']) {
  fs.rmSync(path.join(configTarget, forbidden), { recursive: true, force: true });
}

if (fs.existsSync(zipPath)) fs.rmSync(zipPath);

await new Promise((resolve, reject) => {
  const output = fs.createWriteStream(zipPath);
  const archive = new ZipArchive({ zlib: { level: 9 } });
  output.on('close', resolve);
  output.on('error', reject);
  archive.on('error', reject);
  archive.pipe(output);
  archive.directory(staging, false);
  archive.finalize();
});

const size = fs.statSync(zipPath).size;
console.log(`\nCreated ${zipName} (${(size / 1024 / 1024).toFixed(2)} MB)`);
console.log(`Staging folder: ${staging}`);
if (preview) {
  console.log('Preview package: noindex is enabled. Do not publish it as the production site.');
}
